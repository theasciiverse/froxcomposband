#!/bin/sh
# Builds FroxComposband's terminal (curses) version. Linux: run inside
# alpine:3.22 for a fully static binary; macOS: run on a runner of the
# target architecture, linking the system's ncurses.
#   docker run --rm -v "$PWD":/src -w /src alpine:3.22 sh asciiverse/build.sh
# Leaves src/froxcomposband and the generated help in lib/help.
# With HELP_FROM=<folder>, takes the help pages from there instead.
#
# --with-no-install finds the data in ./lib (the start script runs the game
# from the folder that holds lib/). The two defines are what
# --with-private-dirs adds, which configure won't combine with
# --with-no-install: with them, saves, scores and the data cache go to
# ${XDG_DATA_HOME:-~/.local/share}/FroxComposband instead of into lib/.
# configure only finds curses through an ncursesw*-config script; macOS has
# none, so asciiverse/macos-ncursesw-config stands in for one there.
set -eu
if [ -f /etc/alpine-release ]; then
  apk add --no-cache build-base bash ncurses-dev ncurses-static >/dev/null
  ldflags="-static"
else
  ldflags=""
  if [ "$(uname)" = Darwin ]; then
    NCURSES_CONFIG="$PWD/asciiverse/macos-ncursesw-config"; export NCURSES_CONFIG
  fi
fi
./configure --with-no-install --enable-curses --disable-x11 --disable-sdl --disable-win \
  CPPFLAGS='-DUSE_PRIVATE_PATHS -DPRIVATE_USER_PATH=\"/var/tmp\"' LDFLAGS="$ldflags" >/dev/null
make clean >/dev/null
make
strip src/froxcomposband
# The class, race and monster help pages are generated by a first run, as
# upstream's release does (scripts/release/generate-help.sh). The pages are
# the same on every platform, so, again as upstream does, the macOS builds
# take the ones the Linux build made (HELP_FROM, a folder exported by
# copy_generated_help_export) instead of running the game on the runner.
if [ -n "${HELP_FROM:-}" ]; then
  bash scripts/release/apply-generated-help.sh "$HELP_FROM"
else
  bash scripts/release/generate-help.sh ./src/froxcomposband
  # the script logs the game's run to dist/, which would end up in the release
  rm -rf dist
fi
